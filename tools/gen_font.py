#!/usr/bin/env python3
"""Generate the anti-aliased LCD fonts of LA-F429 (f429/font.c).

Glyphs are rendered from DejaVu Sans Mono with Pillow and stored as 4-bit
coverage values, two pixels per byte (left pixel in the high nibble).
Codes 0x20..0x7E are ASCII; 0x80.. hold the extra symbols listed in EXTRA.

    tools/gen_font.py > f429/font.c

DejaVu fonts: Bitstream Vera / DejaVu licence (free to embed).
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "/usr/share/fonts/truetype/dejavu/"

# name, file, pixel size, cell width, cell height
FONTS = [
    ("font_s", "DejaVuSansMono.ttf", 13, 8, 16),
    ("font_l", "DejaVuSansMono-Bold.ttf", 20, 12, 24),
]

# Extra symbols, starting at code 0x80 (keep in sync with font.h)
EXTRA = ["↑", "↓", "µ", "×", "●", "↕", "Δ"]  # up down micro times dot updown delta

FIRST = 0x20
LAST = 0x80 + len(EXTRA) - 1


def glyph_char(code):
    if code >= 0x80:
        return EXTRA[code - 0x80]
    if code == 0x7F:
        return None
    return chr(code)


def render(file, size, w, h):
    font = ImageFont.truetype(FONT_DIR + file, size)
    ascent, descent = font.getmetrics()
    baseline = (h + ascent - descent) // 2
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = glyph_char(code)
        img = Image.new("L", (w, h), 0)
        if ch is not None and ch != " ":
            d = ImageDraw.Draw(img)
            # centre the advance width in the cell
            adv = font.getlength(ch)
            d.text(((w - adv) / 2, baseline), ch, font=font, fill=255, anchor="ls")
        px = img.tobytes()
        nib = [min(15, (v + 8) // 17) for v in px]
        data = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        glyphs.append((code, ch, data))
    return glyphs


def main():
    out = sys.stdout
    out.write("// Generated by tools/gen_font.py from DejaVu Sans Mono. Do not edit.\n")
    out.write("// 4-bit coverage, 2 pixels per byte, left pixel in the high nibble.\n")
    out.write('#include "font.h"\n\n')
    for name, file, size, w, h in FONTS:
        glyphs = render(file, size, w, h)
        out.write(f"static const uint8_t {name}_bits[] = {{\n")
        for code, ch, data in glyphs:
            label = "DEL" if ch is None else ("U+%04X" % ord(ch) if code >= 0x80 else repr(ch))
            out.write(f"    // 0x{code:02X} {label}\n")
            row = w // 2
            for y in range(h):
                out.write("    " + "".join(f"0x{b:02X}," for b in data[y * row:(y + 1) * row]) + "\n")
        out.write("};\n\n")
        out.write(f"const font_t {name} = {{{w}, {h}, 0x{FIRST:02X}, 0x{LAST:02X}, {name}_bits}};\n\n")


if __name__ == "__main__":
    main()
